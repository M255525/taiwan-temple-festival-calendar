FC.activeOn = function(n){
  var Y = FC.ymd(n).y, out = [];
  [Y - 1, Y].forEach(function(y){
    FC.FESTS.forEach(function(f){ var o = FC.occ(f, y); if (o && o.s != null && o.st !== 'off' && n >= o.s && n <= o.e && !out.some(function(q){ return q.f === f; })) out.push({f:f, o:o}); });
  });
  return out;
};
/* 從 n 起往後找下一次舉辦（最多找到 FC.YMAX） */
FC.nextOf = function(f, n){
  for (var y = FC.ymd(n).y - 1; y <= FC.YMAX; y++){ var o = FC.occ(f, y); if (o && o.s != null && o.st !== 'off' && o.e >= n) return {y:y, o:o}; }
  return null;
};
