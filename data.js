/* 某個國曆年 Y 的舉辦資訊：{st, s, e, subs:[{n,t}], note, next, where} */
FC.occ = function(f, Y){
  var out = {st:'fixed', s:null, e:null, subs:[], note:(f.notes && f.notes[Y]) || '', where:(f.where && f.where[Y]) || null};
  if (f.cycle && (Y - f.cycle.base) % f.cycle.every !== 0){
    out.st = 'off'; var k = Y; while ((k - f.cycle.base) % f.cycle.every !== 0) k++; out.next = k; return out;
  }
  if (f.solar && f.solar[Y]){ out.st = 'year'; out.s = FC.parse(f.solar[Y][0]); out.e = FC.parse(f.solar[Y][1]); }
  else {
    var lr = f.lr || f.approx;
    if (!lr){ out.st = 'approx'; return out; }
    for (var ly = Y - 1; ly <= Y; ly++){
      var r = lrDates(ly, lr); if (!r) continue;
      if (f.sat){ var w = FC.ymd(r[0]).w, back = w === 6 ? 7 : w + 1; r = [r[0] - back, r[0] - back]; }
      if (FC.ymd(r[0]).y === Y){ out.s = r[0]; out.e = r[1]; out.ly = ly; break; }
    }
    if (out.s == null) return null;
    out.st = f.lr ? 'fixed' : 'approx';
    if (f.sat) out.trad = FC.solar(out.ly, f.lr[0][0], f.lr[0][1]);
  }
  if (f.pause && f.pause[Y]){ out.st = 'pause'; out.note = f.pause[Y]; }
  if (f.subs && out.st !== 'approx'){
    var ly2 = out.ly || (FC.lunarOf(out.s) || {}).ly;
    f.subs.forEach(function(sb){ var n = FC.solar(ly2, sb[0][0], sb[0][1]); if (n != null) out.subs.push({n:n, t:sb[1]}); });
    if (out.st === 'year') out.subs = [];
  }
  return out;
};
