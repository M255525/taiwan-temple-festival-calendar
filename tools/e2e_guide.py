# 廟宇深度導覽圖錄端對端：python tools/e2e_guide.py <截圖資料夾>（需先開 http://127.0.0.1:8886；FEST_BASE 可測線上版）
import sys, io, os
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', line_buffering=True)
from playwright.sync_api import sync_playwright
OUT = sys.argv[1]; os.makedirs(OUT, exist_ok=True)
BASE = os.environ.get('FEST_BASE', 'http://127.0.0.1:8886/')
errs, fails = [], []
def check(c, msg):
    print(('ok   ' if c else 'FAIL ') + msg)
    if not c: fails.append(msg)
def stub(pg, tag):
    pg.route('**/script.google.com/**', lambda r: r.fulfill(status=200, body='{"marquee":[]}', headers={'content-type': 'application/json'}))
    pg.route('**/visitor-badge.laobi.icu/**', lambda r: r.fulfill(status=200, body='', headers={'content-type': 'image/svg+xml'}))
    pg.on('pageerror', lambda e: errs.append(tag + ': ' + str(e)))
    pg.on('console', lambda m: m.type == 'error' and 'Failed to load resource' not in m.text and errs.append(tag + ': ' + m.text))
with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    ctx = b.new_context(viewport={'width': 1440, 'height': 900})
    ctx.add_init_script("localStorage.setItem('taiwanFestSeenWarning','1')")
    t = ctx.new_page(); stub(t, 'D')
    t.goto(BASE + '#d=2026-04-18', wait_until='domcontentloaded'); t.wait_for_function('window.FestScene && FestScene.ready', timeout=60000); t.wait_for_timeout(1200)
    t.click('#btnGuide'); t.wait_for_timeout(300)
    check(t.is_visible('#guide.show'), '開啟廟宇圖錄')
    check(t.locator('.tg-card').count() == 24, '24 座廟卡片 %d' % t.locator('.tg-card').count())
    check(t.locator('.tg-card svg.fac').count() == 24, '每張卡都有立面圖')
    t.screenshot(path=os.path.join(OUT, 'g1_list.png'))
    t.check('#tgHerit'); t.wait_for_timeout(100); nh = t.locator('.tg-card').count()
    check(10 < nh < 24, '只看古蹟 %d' % nh)
    t.uncheck('#tgHerit'); t.select_option('#tgGod', 'mazu'); t.wait_for_timeout(100)
    check(t.locator('.tg-card').count() >= 7, '媽祖廟 %d' % t.locator('.tg-card').count())
    t.select_option('#tgGod', ''); t.fill('#tgQ', '藻井'); t.wait_for_timeout(100)
    check(t.locator('.tg-card').count() >= 3, '搜尋藻井 %d' % t.locator('.tg-card').count())
    t.fill('#tgQ', '')
    t.click('.tg-card[data-t="lukang-longshan"]'); t.wait_for_timeout(300)
    d = t.inner_text('#tgDetail')
    check('鹿港龍山寺' in d and '國定古蹟' in d and '八卦藻井' in d and '建議參觀動線' in d, '詳細頁內容')
    t.screenshot(path=os.path.join(OUT, 'g2_detail.png'))
    t.click('#tgDetail [data-map]'); t.wait_for_timeout(1800)
    check(not t.is_visible('#guide.show') and t.evaluate('FestScene.pinInfo()') is not None, '在地圖上看：關閉圖錄並放金色箭頭')
    check(t.locator('.plab.tpin:not(.off)').count() == 1, '地圖上顯示廟名標籤')
    t.screenshot(path=os.path.join(OUT, 'g3_pin.png'))
    t.click('#btnAll'); t.wait_for_timeout(500)
    check(t.evaluate('FestScene.pinInfo()') is None, '看全台灣時收掉箭頭')
    t.evaluate("TempleGuide.open('beigang-chaotian')"); t.wait_for_timeout(300)
    t.click('#tgDetail [data-fest]'); t.wait_for_timeout(800)
    check(t.evaluate('__fest.state.fest') == 'beigang', '從圖錄跳到北港迎媽祖廟會')
    t.click('#btnTemple'); t.wait_for_timeout(300)
    check(t.is_visible('#guide.show') and '北港朝天宮' in t.inner_text('#tgDetail h3'), '廟會面板的「導覽」按鈕回到圖錄')
    t.click('.tg-tab[data-tab="intro"]'); t.wait_for_timeout(300)
    check(t.locator('#tgIntro .hot').count() == 13, '看廟入門 13 個熱點')
    t.click('#tgIntro .hot[data-part="column"]'); t.wait_for_timeout(100)
    check('龍柱' in t.inner_text('#tgPart'), '點熱點顯示說明')
    t.screenshot(path=os.path.join(OUT, 'g4_intro.png'))
    t.keyboard.press('Escape'); t.wait_for_timeout(200)
    check(not t.is_visible('#guide.show'), 'Esc 關閉')
    # 分享連結 #t=
    t.goto(BASE + '#d=2026-04-18&t=penghu-tianhou', wait_until='domcontentloaded'); t.wait_for_timeout(2500)
    check(t.is_visible('#guide.show') and '澎湖天后宮' in t.inner_text('#tgDetail'), '網址 #t= 直接開詳細頁')
    t.close()
    # 手機
    m = ctx.new_page(); stub(m, 'M'); m.set_viewport_size({'width': 375, 'height': 760})
    m.goto(BASE + '#d=2026-04-18&t=tainan-wumiao', wait_until='domcontentloaded'); m.wait_for_timeout(3000)
    sw = m.evaluate('document.querySelector("#guide .sheet").scrollWidth <= document.querySelector("#guide .sheet").clientWidth + 1')
    check(sw, '375px 圖錄無橫向捲動')
    m.screenshot(path=os.path.join(OUT, 'g5_mobile.png'))
    m.click('#tgDetail [data-back]'); m.wait_for_timeout(200); m.screenshot(path=os.path.join(OUT, 'g6_mobile_list.png'))
    b.close()
print('console errors:', errs)
print('FAILS:', fails if fails else 'none')
