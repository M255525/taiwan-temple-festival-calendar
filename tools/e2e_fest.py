# 端對端：python tools/e2e_fest.py <截圖資料夾>（需先開 http://127.0.0.1:8886；FEST_BASE 可測線上版）
import sys, io, os
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', line_buffering=True)
from playwright.sync_api import sync_playwright
OUT = sys.argv[1]; os.makedirs(OUT, exist_ok=True)
BASE = os.environ.get('FEST_BASE', 'http://127.0.0.1:8886/')
errs, fails = [], []
def check(c, msg):
    print(('ok   ' if c else 'FAIL ') + msg)
    if not c: fails.append(msg)
def stub(pg, tag):
    pg.route('**/script.google.com/**', lambda r: r.fulfill(status=200, body='{"marquee":["測試公告：跑馬燈正常"]}', headers={'content-type': 'application/json'}))
    pg.route('**/visitor-badge.laobi.icu/**', lambda r: r.fulfill(status=200, body='', headers={'content-type': 'image/svg+xml'}))
    pg.on('pageerror', lambda e: errs.append(tag + ': ' + str(e)))
    pg.on('console', lambda m: m.type == 'error' and 'Failed to load resource' not in m.text and errs.append(tag + ': ' + m.text))
def shot(pg, name): pg.screenshot(path=os.path.join(OUT, name))
with sync_playwright() as p:
    b = p.chromium.launch(args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    ctx = b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
    t = ctx.new_page(); stub(t, 'D')
    t.goto(BASE + '#d=2026-04-18', wait_until='domcontentloaded'); t.wait_for_function('window.FestScene && FestScene.ready', timeout=60000); t.wait_for_timeout(1500)
    check(t.is_visible('#about.show'), '首訪跳出警語')
    t.click('#about .x'); t.wait_for_timeout(300)
    s = t.evaluate('FestScene.stats()')
    check(s['spots'] == len(t.evaluate('__fest.FC.FESTS')) == 21, '21 座廟 %s' % s['spots'])
    check(s['state']['dajia'] == 'live' and s['state']['baishatun'] == 'live', '4/18 大甲媽與白沙屯在辦')
    check('農曆三月初二' in t.inner_text('#daySub'), '日期框顯示農曆 ' + t.inner_text('#daySub'))
    shot(t, '01_0418.png')
    t.evaluate("__fest.selectFest('dajia')"); t.wait_for_timeout(1800)
    txt = t.inner_text('#place')
    check('4/17（五）～4/26（日）' in txt and '已公告' in txt, '大甲媽 2026 已公告日期')
    shot(t, '02_dajia.png')
    t.evaluate("__fest.setDay(__fest.FC.parse('2026-08-26')); __fest.selectFest('keelung')"); t.wait_for_timeout(1800)
    txt = t.inner_text('#place')
    check('水燈頭遊行' in txt and '七月十四' in t.inner_text('#sum'), '8/26（農曆七月十四）雞籠中元祭日程有放水燈')
    shot(t, '03_keelung.png')
    t.evaluate("__fest.setDay(__fest.FC.parse('2027-02-20')); __fest.selectFest(null)"); t.wait_for_timeout(1500)
    s = t.evaluate('FestScene.stats()')
    live = [k for k, v in s['state'].items() if v == 'live']
    check(set(['yanshui', 'handan', 'pingxi', 'miaoli']) <= set(live), '2027 元宵：蜂炮、寒單、天燈、火旁龍同時在辦 %s' % live)
    check('元宵節' in t.inner_text('#place'), '元宵節標記')
    shot(t, '04_lantern2027.png')
    t.evaluate("__fest.selectFest('donggang')"); t.wait_for_timeout(1200)
    check('大約' in t.inner_text('#place') and '日期待公告' in t.inner_text('#place'), '東港迎王 2027 顯示大約＋待公告')
    t.evaluate("__fest.setDay(__fest.FC.parse('2026-06-01'))"); t.wait_for_timeout(500)
    check('沒有舉辦' in t.inner_text('#place') or '2027' in t.inner_text('#place'), '東港迎王 2026 沒有、下一科 2027')
    t.evaluate("__fest.setDay(__fest.FC.parse('2026-04-25')); __fest.selectFest('xuejia')"); t.wait_for_timeout(800)
    check('傳統日期' in t.inner_text('#place'), '學甲上白礁顯示傳統日期')
    with t.expect_download() as d: t.click('#btnIcs')
    pth = os.path.join(OUT, 'x.ics'); d.value.save_as(pth); ics = open(pth, encoding='utf-8').read()
    check('DTSTART;VALUE=DATE:20260425' in ics and 'END:VCALENDAR' in ics, '.ics 下載')
    check('#d=2026-04-25&f=xuejia' in t.url, '網址帶分享參數')
    t.reload(); t.wait_for_function('window.FestScene && FestScene.ready', timeout=60000); t.wait_for_timeout(800)
    check(t.evaluate('__fest.state.fest') == 'xuejia' and '4/25' in t.inner_text('#dayBig'), '重新整理依網址還原')
    # 拖曳日期軸
    bb = t.locator('#axCv').bounding_box(); t.mouse.click(bb['x'] + bb['width'] * .62, bb['y'] + bb['height'] / 2); t.wait_for_timeout(300)
    check(t.evaluate('__fest.FC.ymd(__fest.state.day).m') in (8, 9), '點日期軸跳到 8～9 月 %s' % t.inner_text('#dayBig'))
    t.click('#yNext'); t.wait_for_timeout(300)
    check(t.inner_text('#yearTxt') == '2027', '下一年')
    t.click('#btnEtq'); t.wait_for_timeout(200); check(t.is_visible('#etq.show'), '節慶須知'); t.keyboard.press('Escape')
    t.click('#btnSet'); t.wait_for_timeout(200); check(t.is_visible('#settings.show'), '常用設定'); t.keyboard.press('Escape')
    m = ctx.new_page(); stub(m, 'M'); m.set_viewport_size({'width': 375, 'height': 760})
    m.goto(BASE + '#d=2026-05-05', wait_until='domcontentloaded'); m.wait_for_function('window.FestScene && FestScene.ready', timeout=60000); m.wait_for_timeout(1200)
    check(m.evaluate('document.documentElement.scrollWidth <= innerWidth'), '375px 無橫向捲動')
    shot(m, '05_mobile.png')
    print('console 錯誤：', errs[:6]); check(not errs, '沒有 console 錯誤')
    b.close()
print('\n失敗 %d 項' % len(fails) + ('：' + '；'.join(fails) if fails else ''))
sys.exit(1 if fails else 0)
